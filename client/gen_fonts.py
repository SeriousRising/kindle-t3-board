#!/usr/bin/env python3
"""
Generate client/font_atlas.h with pre-rasterized 8-bit antialiased grayscale
glyphs from DejaVu Sans / DejaVu Sans Mono (ASCII 32..126) for zero-dependency
e-ink framebuffer rendering on the Kindle Touch D01200.
"""

from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

OUT_PATH = Path(__file__).resolve().parent / "font_atlas.h"

SANS_BOLD = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
MONO_REG = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
MONO_BOLD = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"

FONTS = [
    ("FONT_MONO_12",      MONO_REG,  12),
    ("FONT_MONO_13_BOLD", MONO_BOLD, 13),
    ("FONT_MONO_14_BOLD", MONO_BOLD, 14),
    ("FONT_SANS_15_BOLD", SANS_BOLD, 15),
    ("FONT_SANS_22_BOLD", SANS_BOLD, 22),
    ("FONT_SANS_24_BOLD", SANS_BOLD, 24),
    ("FONT_SANS_68_BOLD", SANS_BOLD, 68),
]

FIRST_CHAR = 32
LAST_CHAR = 126


def rasterize_font(c_name: str, ttf_path: str, px_size: int):
    font = ImageFont.truetype(ttf_path, px_size)
    ascent, descent = font.getmetrics()
    line_height = ascent + descent

    glyphs = []
    bitmap_bytes = bytearray()

    for code in range(FIRST_CHAR, LAST_CHAR + 1):
        ch = chr(code)
        adv = int(round(font.getlength(ch)))
        bbox = font.getbbox(ch, anchor="ls")  # baseline origin
        if bbox is None or ch == " ":
            glyphs.append((0, 0, 0, 0, max(adv, px_size // 3), 0))
            continue

        x0, y0, x1, y1 = bbox
        w = max(0, x1 - x0)
        h = max(0, y1 - y0)
        if w == 0 or h == 0:
            glyphs.append((0, 0, 0, 0, max(adv, 1), 0))
            continue

        # Render onto tight canvas
        img = Image.new("L", (w, h), 0)
        draw = ImageDraw.Draw(img)
        draw.text((-x0, -y0), ch, fill=255, font=font, anchor="ls")
        data = img.tobytes()

        offset = len(bitmap_bytes)
        bitmap_bytes.extend(data)
        glyphs.append((w, h, x0, y0, max(adv, 1), offset))

    return {
        "name": c_name,
        "px_size": px_size,
        "ascent": ascent,
        "descent": descent,
        "line_height": line_height,
        "glyphs": glyphs,
        "bitmap": bytes(bitmap_bytes),
    }


def main():
    rendered = [rasterize_font(name, path, sz) for name, path, sz in FONTS]
    total_bytes = sum(len(f["bitmap"]) for f in rendered)

    lines = [
        "/* Auto-generated by gen_fonts.py — do not edit manually */",
        "#ifndef T3_FONT_ATLAS_H",
        "#define T3_FONT_ATLAS_H",
        "",
        "#include <stdint.h>",
        "",
        f"#define FONT_FIRST_CHAR {FIRST_CHAR}",
        f"#define FONT_LAST_CHAR  {LAST_CHAR}",
        "",
        "typedef struct {",
        "    uint8_t  w;",
        "    uint8_t  h;",
        "    int8_t   xoff;",
        "    int8_t   yoff;",
        "    uint8_t  advance;",
        "    uint32_t offset;",
        "} GlyphInfo;",
        "",
        "typedef struct {",
        "    uint8_t px_size;",
        "    uint8_t ascent;",
        "    uint8_t line_height;",
        "    const GlyphInfo *glyphs;",
        "    const uint8_t   *bitmap;",
        "} BitmapFont;",
        "",
    ]

    for f in rendered:
        n = f["name"]
        lines.append(f"static const uint8_t {n}_BITMAP[{max(1, len(f['bitmap']))}] = {{")
        bm = f["bitmap"]
        for i in range(0, len(bm), 16):
            chunk = ", ".join(f"{b}" for b in bm[i:i + 16])
            lines.append(f"    {chunk},")
        lines.append("};")
        lines.append("")
        lines.append(f"static const GlyphInfo {n}_GLYPHS[{LAST_CHAR - FIRST_CHAR + 1}] = {{")
        for g in f["glyphs"]:
            w, h, xo, yo, adv, off = g
            lines.append(f"    {{ {w}, {h}, {xo}, {yo}, {adv}, {off} }},")
        lines.append("};")
        lines.append("")
        lines.append(f"static const BitmapFont {n} = {{")
        lines.append(f"    {f['px_size']}, {f['ascent']}, {f['line_height']}, {n}_GLYPHS, {n}_BITMAP")
        lines.append("};")
        lines.append("")

    lines.append("#endif /* T3_FONT_ATLAS_H */")
    OUT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT_PATH} ({len(rendered)} fonts, {total_bytes:,} bitmap bytes)")


if __name__ == "__main__":
    main()
